export const SYSTEM_ROLE_KEYS = new Set(SYSTEM_ROLES.map((r) => r.key));

/** Validate the seed catalog eagerly so a typo fails at boot. */
export function validateSystemRoleCatalog(): void {
  const known = new Set(PERMISSION_CATALOG.map((p) => p.key));
  for (const role of SYSTEM_ROLES) {
    for (const key of role.permissions) {
      if (!known.has(key)) {
        throw new Error(`Unknown permission "${key}" in system role "${role.key}"`);
      }
    }
  }
}

